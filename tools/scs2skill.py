#!/usr/bin/env python3
"""Spectre subckt netlists -> SKILL that draws schematics + symbols in Virtuoso. Runs on Windows.

    python tools/scs2skill.py -o skill/gen_cells_A.il ALU_CELLS_A=cells/A ALU_STUB_B=cells/_stub_B
    python tools/scs2skill.py -o skill/gen_ksa.il --ref ALU_CELLS_A=cells/A ALU_ADD=blocks/ALU_ADD/KSA8.scs

LIB=path: path is a .scs file or a directory scanned for <CELL>/<CELL>.scs (tb_*.scs skipped).
Every subckt found becomes one cell of LIB. --ref LIB=path: cells that already exist in
Virtuoso (only read, to know their pins); they are not regenerated.
Instances: 'NAME (nodes) MASTER k=v ...'. MASTER is a gpdk090 device (PRIM) or a subckt.
Pin direction: VDD/VSS -> inputOutput; a pin driven by a MOS drain/source or by a
sub-instance output -> output; anything else -> input.
The generated file loads skill/sch_build.il (sbCell etc.) and is run in the VM:
    cd ~/ALU_PROJ && virtuoso -nograph -restore /mnt/hgfs/Share/VLSI_work/skill/gen_cells_A.il
"""
import argparse
import re
import sys
from pathlib import Path

# spectre device -> (Virtuoso lib, cell, symbol terminal names in spectre node order)
PRIM = {"gpdk090_nmos1v": ("gpdk090", "nmos1v", ["D", "G", "S", "B"]),
        "gpdk090_pmos1v": ("gpdk090", "pmos1v", ["D", "G", "S", "B"])}
SUPPLY = {"VDD", "VSS"}
SUFFIX = {"f": 1e-15, "p": 1e-12, "n": 1e-9, "u": 1e-6, "m": 1e-3, "k": 1e3, "M": 1e6, "G": 1e9}


def num(s):
    m = re.fullmatch(r"([-+]?[0-9.]+(?:[eE][-+]?\d+)?)([fpnumkMG]?)", s)
    return float(m.group(1)) * SUFFIX.get(m.group(2), 1) if m else None


def eng(v):
    """240e-9 -> '240n' (CDF length strings)."""
    for suf in "fpnum":
        x = v / SUFFIX[suf]
        if abs(x) < 1000:
            return f"{round(x, 6):g}{suf}"
    return f"{v:g}"


def parse(path, top=None):
    """-> {cell: {"pins": [...], "insts": [(name, master, nodes, {param: value})]}}
    top: also collect top-level instances (outside any subckt) as cell `top`."""
    text = re.sub(r"\\\n", " ", Path(path).read_text())
    cells, cur = {}, None
    if top:
        cells[top] = {"pins": [], "insts": [], "file": str(path)}
    for raw in text.splitlines():
        line = raw.split("//")[0].strip()
        if not line or line[0] in "*#":
            continue
        tok = line.split()
        if tok[0] == "inline":
            tok = tok[1:]
        if tok[0] == "subckt":
            cur = cells[tok[1]] = {"pins": tok[2:], "insts": [], "file": str(path)}
        elif tok[0] == "ends":
            cur = None
        elif cur is not None or top:
            m = re.fullmatch(r"(\S+)\s*\(([^)]*)\)\s*(\S+)(.*)", line)
            if not m:
                if cur is None:
                    continue    # top-level statement (options, analyses ...)
                sys.exit(f"{path}: cannot parse instance line: {raw}")
            if cur is None and m.group(3) in ("vsource", "isource"):
                continue
            params = dict(kv.split("=", 1) for kv in m.group(4).split())
            (cur or cells[top])["insts"].append((m.group(1), m.group(3), m.group(2).split(), params))
    return cells


def collect(spec):
    lib, _, p = spec.partition("=")
    p = Path(p)
    files = [p] if p.is_file() else sorted(f for f in p.glob("*/*.scs") if f.stem == f.parent.name)
    if not files:
        sys.exit(f"no netlists in {p}")
    out = {}
    for f in files:
        for cell, c in parse(f).items():
            c["lib"] = lib
            out[cell] = c
    return out


def directions(cells):
    order, dirs = [], {}

    def visit(name, stack=()):
        if name in dirs:
            return
        if name in stack:
            sys.exit(f"recursive subckt {name}")
        c = cells[name]
        driven = set()
        for inst, master, nodes, _ in c["insts"]:
            if master in PRIM:
                if len(nodes) != 4:
                    sys.exit(f"{name}/{inst}: {master} needs 4 nodes")
                driven |= {nodes[0], nodes[2]}
                continue
            if master not in cells:
                sys.exit(f"{name}/{inst}: unknown master {master}")
            visit(master, stack + (name,))
            mp = cells[master]["pins"]
            if len(mp) != len(nodes):
                sys.exit(f"{name}/{inst}: {master} has {len(mp)} pins, got {len(nodes)} nodes")
            driven |= {n for n, p in zip(nodes, mp) if dirs[master][p] == "output"}
        dirs[name] = {p: "inputOutput" if p in SUPPLY else "output" if p in driven else "input"
                      for p in c["pins"]}
        order.append(name)

    for name in cells:
        visit(name)
    return order, dirs


def q(s):
    return '"' + s + '"'


def emit(cells, order, dirs, gen, sources):
    L = [";; generated by tools/scs2skill.py from " + " ".join(sources) + " -- do not edit",
         ";; run in the VM:  cd ~/ALU_PROJ && virtuoso -nograph -restore <this file> < /dev/null",
         ";; run with < /dev/null; any SKILL error -> message + exit, never a hanging CIW prompt",
         "unless(errset(progn(",
         'sbDir = or(getShellEnvVar("SB_DIR") "/mnt/hgfs/Share/VLSI_work/skill")',
         'load(strcat(sbDir "/sch_build.il"))',
         "sbBegin()"]
    for lib in dict.fromkeys(cells[c]["lib"] for c in order if c in gen):
        L.append(f'sbLib({q(lib)} "gpdk090")')
    for name in order:
        if name not in gen:
            continue
        c = cells[name]
        pins = " ".join(f"({q(p)} {q(dirs[name][p])})" for p in c["pins"])
        insts = []
        for inst, master, nodes, params in c["insts"]:
            if master in PRIM:
                mlib, mcell, terms = PRIM[master]
                cdf = {k: eng(num(v)) if num(v) is not None else v for k, v in params.items()}
                if "w" in cdf:     # gpdk090 CDF: netlist uses fw (finger width); 1 finger
                    cdf = {"fingers": "1", "w": cdf["w"], "fw": cdf["w"], **cdf}
                ps = [f"({q(k)} {q(v)})" for k, v in cdf.items()]
            else:
                mlib, mcell, terms, ps = cells[master]["lib"], master, cells[master]["pins"], []
            conn = " ".join(f"({q(t)} {q(n)})" for t, n in zip(terms, nodes))
            insts.append(f"  ({q(inst)} {q(mlib)} {q(mcell)} ({conn}) ({' '.join(ps)}))")
        # per-cell errset: one failing cell never stops the others
        L.append(f"unless(errset(sbCell({q(c['lib'])} {q(name)} '({pins})\n '(\n" + "\n".join(insts) +
                 f")) t)\n  sbErrors++ printf(\"SB_ERROR {name}: %L\\n\" errset.errset))")
    L += ["sbEnd()) t)", r'  printf("SB_ERROR uncaught: %L\n" errset.errset)', "  exit(2))", "exit(3)   ; unconditional: -nograph never exits on stdin EOF", ""]
    return "\n".join(L)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("-o", "--out", required=True)
    ap.add_argument("--ref", action="append", default=[], help="LIB=path, existing cells (not regenerated)")
    ap.add_argument("libs", nargs="+", help="LIB=path")
    a = ap.parse_args()
    cells = {}
    for s in a.ref:
        cells.update(collect(s))
    gen = {}
    for s in a.libs:
        gen.update(collect(s))
    cells.update(gen)
    order, dirs = directions(cells)
    Path(a.out).write_text(emit(cells, order, dirs, gen, a.ref + a.libs), encoding="ascii", newline="\n")
    for n in order:
        if n in gen:
            print(f"{cells[n]['lib']}/{n}: {len(cells[n]['insts'])} inst, pins " +
                  " ".join(f"{p}:{d[0:3]}" for p, d in dirs[n].items()))


if __name__ == "__main__":
    main()
