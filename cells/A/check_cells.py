#!/usr/bin/env python3
"""Testbench generator + result checker for A's cells (and B's stubs). Runs on Windows.

    python cells/A/check_cells.py gen                 # (re)write tb_<CELL>.scs next to each cell
    python tools/vmjob.py --label cells -c "bash cells/A/run_cells.sh NN FF SS"
    python cells/A/check_cells.py check               # read out/cells/<corner>/<CELL>/tr.tran

Stimulus: an Euler circuit of the input hypercube, so every vector is visited and every
single-input transition (each arc, both directions) happens once. Each vector lasts T,
edges are 20 ps. Truth table is checked at the end of every vector (output within 10% of
the rail); tpLH/tpHL are measured 50%->50% on every arc and the worst arc is reported.
Each output is loaded with 4x INV_X1 (FO4).
"""
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = Path(os.environ.get("VLSI_OUT", r"D:\Hoc\VLSI_Design\Share\VLSI_work\out")) / "cells"
MODEL = "/home/buet/cadence/gpdk090_v4.6/models/spectre/gpdk090.scs"
VDD = 1.2
T_PS, TR_PS = 500, 20
T_CELL = {"CMP42": 1000, "CAS_X1": 1000}   # 2 FA in series: ~490 ps at SS, too close to the 500 ps period

# cell -> (dir, {output: logic function of the input dict})
CELLS = {
    "INV_X1":   ("cells/A", {"Y": lambda v: not v["A"]}),
    "NAND2_X1": ("cells/A", {"Y": lambda v: not (v["A"] and v["B"])}),
    "NOR2_X1":  ("cells/A", {"Y": lambda v: not (v["A"] or v["B"])}),
    "AOI21_X1": ("cells/A", {"Y": lambda v: not (v["A1"] and v["A2"] or v["B"])}),
    "OAI21_X1": ("cells/A", {"Y": lambda v: not ((v["A1"] or v["A2"]) and v["B"])}),
    "BLK_P": ("cells/A", {"GON": lambda v: not (v["GI"] or v["PI"] and v["GK"]),
                          "PON": lambda v: not (v["PI"] and v["PK"])}),
    "BLK_N": ("cells/A", {"GO": lambda v: not (v["GIN"] and (v["PIN"] or v["GKN"])),
                          "PO": lambda v: not (v["PIN"] or v["PKN"])}),
    "GRY_P": ("cells/A", {"GON": lambda v: not (v["GI"] or v["PI"] and v["GK"])}),
    "GRY_N": ("cells/A", {"GO": lambda v: not (v["GIN"] and (v["PIN"] or v["GKN"]))}),
    "XOR2_X1":  ("cells/_stub_B", {"Y": lambda v: v["A"] != v["B"]}),
    "XNOR2_X1": ("cells/_stub_B", {"Y": lambda v: v["A"] == v["B"]}),
    # multiplier cells (B, C), netlists written by blocks/ALU_MUL/gen_mul.py
    "FA_X1": ("cells/C", {"S": lambda v: (v["A"] + v["B"] + v["CI"]) % 2 == 1,
                          "CO": lambda v: v["A"] + v["B"] + v["CI"] >= 2}),
    "HA_X1": ("cells/C", {"S": lambda v: v["A"] != v["B"], "CO": lambda v: v["A"] and v["B"]}),
    "BOOTH_ENC": ("cells/B", {"ONE": lambda v: v["X1"] != v["X0"],
                              "TWO": lambda v: (v["X2"], v["X1"], v["X0"]) in ((0, 1, 1), (1, 0, 0))}),
    "BOOTH_SEL": ("cells/B", {"PP": lambda v: bool(v["ONE"] and v["AJ"] or v["TWO"] and v["AJM"]) != bool(v["NEG"])}),
    "CMP42": ("cells/B", {"S": lambda v: (v["X1"] + v["X2"] + v["X3"] + v["X4"] + v["CI"]) % 2 == 1,
                          "C": lambda v: (v["X1"] ^ v["X2"] ^ v["X3"]) + v["X4"] + v["CI"] >= 2,
                          "CO": lambda v: v["X1"] + v["X2"] + v["X3"] >= 2}),
    # divider cell (D), netlist written by blocks/ALU_DIV/gen_div.py
    "CAS_X1": ("cells/D", {"S": lambda v: (v["X"] + (v["D"] ^ v["T"]) + v["CI"]) % 2 == 1,
                           "CO": lambda v: v["X"] + (v["D"] ^ v["T"]) + v["CI"] >= 2}),
}
CORNERS = ["NN", "FF", "SS"]


def pins(cell):
    d, outs = CELLS[cell]
    for line in (ROOT / d / cell / f"{cell}.scs").read_text().splitlines():
        tok = line.split()
        if tok[:2] == ["subckt", cell]:
            p = tok[2:]
            ins = [x for x in p if x not in outs and x not in ("VDD", "VSS")]
            assert p == ins + list(outs) + ["VDD", "VSS"], f"{cell}: pin order {p}"
            return p, ins, list(outs)
    raise SystemExit(f"{cell}: subckt line not found")


def euler(n):
    """Vertex sequence of an Euler circuit of the directed n-cube (n*2^n arcs)."""
    adj = {v: [v ^ (1 << i) for i in range(n)] for v in range(1 << n)}
    stack, path = [0], []
    while stack:
        if adj[stack[-1]]:
            stack.append(adj[stack[-1]].pop())
        else:
            path.append(stack.pop())
    path.reverse()
    assert len(path) == n * (1 << n) + 1 and len({(a, b) for a, b in zip(path, path[1:])}) == n << n
    return path


def bits(v, ins):
    # ins[0] is the MSB of the vector number
    n = len(ins)
    return {x: (v >> (n - 1 - i)) & 1 for i, x in enumerate(ins)}


def gen():
    inv = ROOT / "cells/A/INV_X1/INV_X1.scs"
    for cell, (d, outs) in CELLS.items():
        p, ins, _ = pins(cell)
        seq = euler(len(ins))
        T_PS = T_CELL.get(cell, globals()["T_PS"])
        tbdir = ROOT / d / cell
        L = ["// generated by cells/A/check_cells.py gen -- do not edit by hand",
             f"// {cell}: {len(seq)} vectors x {T_PS} ps, edges {TR_PS} ps, FO4 (4x INV_X1) per output",
             "// vector sequence (" + " ".join(ins) + "): " + " ".join(format(v, f"0{len(ins)}b") for v in seq),
             "simulator lang=spectre",
             "global 0",
             f'include "{MODEL}" section=NN']
        if d == "cells/A":      # A's library file (every A cell once, incl. INV_X1 for the load)
            L.append('include "../cells_A.scs"')
        elif d == "cells/D":    # CAS_X1 is built from A's NAND2 + XOR2 stub cells
            L += ['include "../../A/cells_A.scs"', 'include "../../_stub_B/XOR2_X1/XOR2_X1.scs"',
                  f'include "{cell}.scs"']
        else:
            L += [f'include "{cell}.scs"',
                  f'include "{os.path.relpath(inv, tbdir).replace(os.sep, "/")}"']
        L += ["parameters vdd=1.2",
              "Vvdd (VDD 0) vsource dc=vdd",
              "Vvss (VSS 0) vsource dc=0"]
        for x in ins:
            vals = [bits(v, ins)[x] for v in seq]
            w = [f"0 {vals[0] * VDD}"]
            for k in range(1, len(seq)):
                if vals[k] != vals[k - 1]:
                    t = k * T_PS
                    w.append(f"{t}p {vals[k - 1] * VDD} {t + TR_PS}p {vals[k] * VDD}")
            L.append(f"V{x} ({x} 0) vsource type=pwl wave=[ " + " ".join(w) + " ]")
        L.append(f"XDUT ({' '.join(p)}) {cell}")
        for y in outs:
            L += [f"XL_{y}_{i} ({y} L_{y}_{i} VDD VSS) INV_X1" for i in range(4)]
        L += ["saveOpts options save=selected",
              "save " + " ".join(ins + list(outs)),
              f"tr tran stop={len(seq) * T_PS}p maxstep=1p errpreset=conservative", ""]
        (tbdir / f"tb_{cell}.scs").write_text("\n".join(L), encoding="ascii", newline="\n")
        print(f"wrote {d}/{cell}/tb_{cell}.scs ({len(seq)} vectors)")


def read_psfascii(path):
    sweep, names, data, sec = None, [], {}, None
    cur = None
    for line in open(path, encoding="ascii", errors="replace"):
        s = line.strip()
        if s in ("HEADER", "TYPE", "SWEEP", "TRACE", "VALUE", "END"):
            sec = s
            continue
        if not s.startswith('"'):
            continue
        name, _, rest = s[1:].partition('"')
        if sec == "SWEEP" and sweep is None:
            sweep = name
            data[name] = []
        elif sec == "TRACE":
            names.append(name)
            data[name] = []
        elif sec == "VALUE" and name in data:
            val = float(rest.split()[0])
            if name == sweep:
                cur = val
            data[name].append(val)
    return data[sweep], {n: data[n] for n in names}


def at(t, ts, ys):
    lo, hi = 0, len(ts) - 1
    while hi - lo > 1:
        mid = (lo + hi) // 2
        if ts[mid] <= t:
            lo = mid
        else:
            hi = mid
    if ts[hi] == ts[lo]:
        return ys[lo]
    return ys[lo] + (ys[hi] - ys[lo]) * (t - ts[lo]) / (ts[hi] - ts[lo])


def cross(ts, ys, t0, t1, rising):
    """First 50% crossing in [t0, t1] in the given direction (linear interpolation)."""
    th = VDD / 2
    i = max(0, next((k for k, t in enumerate(ts) if t >= t0), len(ts)) - 1)
    while i + 1 < len(ts) and ts[i] <= t1:
        a, b = ys[i], ys[i + 1]
        if (rising and a < th <= b) or (not rising and a > th >= b):
            return ts[i] + (th - a) * (ts[i + 1] - ts[i]) / (b - a)
        i += 1
    return None


def check_one(cell, tran):
    _, ins, outs = pins(cell)
    seq = euler(len(ins))
    ts, w = read_psfascii(tran)
    T, fn = T_CELL.get(cell, T_PS) * 1e-12, CELLS[cell][1]
    errs, ok = [], 0
    worst = {y: {"LH": (0.0, ""), "HL": (0.0, "")} for y in outs}
    for k, v in enumerate(seq):
        b = bits(v, ins)
        for y in outs:
            exp = 1 if fn[y](b) else 0
            vy = at((k + 1) * T - 10e-12, ts, w[y])
            good = vy > 0.9 * VDD if exp else vy < 0.1 * VDD
            ok += good
            if not good:
                errs.append(f"vec#{k} {b} {y}={vy:.3f} V expect {exp}")
            if k == 0:
                continue
            pb = bits(seq[k - 1], ins)
            pexp = 1 if fn[y](pb) else 0
            if pexp == exp:
                continue
            x = next(i for i in ins if pb[i] != b[i])
            tin = cross(ts, w[x], k * T - 5e-12, k * T + T, bool(b[x]))
            tout = cross(ts, w[y], k * T - 5e-12, k * T + T, bool(exp))
            if tin is None or tout is None:
                errs.append(f"vec#{k} {y}: no 50% crossing")
                continue
            kind = "LH" if exp else "HL"
            d = tout - tin
            if d > worst[y][kind][0]:
                arc = " ".join(f"{i}={pb[i]}" for i in ins if i != x)
                worst[y][kind] = (d, f"{x}{'r' if b[x] else 'f'} ({arc})" if arc else f"{x}{'r' if b[x] else 'f'}")
    return ok, len(seq) * len(outs), errs, worst


def check():
    rows, bad = [], 0
    for cell in CELLS:
        for c in CORNERS:
            tran = OUT / c / cell / "tr.tran"
            if not tran.exists():
                print(f"MISSING {tran}")
                bad += 1
                continue
            ok, n, errs, worst = check_one(cell, tran)
            bad += bool(errs)
            for e in errs[:5]:
                print(f"FAIL {cell} {c}: {e}")
            for y, wv in worst.items():
                rows.append((cell, c, y, ok, n, wv["LH"], wv["HL"]))
    print("\n| Cell | Corner | Out | Truth (pass/total) | tpLH (ps) | worst arc LH | tpHL (ps) | worst arc HL |")
    print("|---|---|---|---|---|---|---|---|")
    for cell, c, y, ok, n, lh, hl in rows:
        print(f"| {cell} | {c} | {y} | {ok}/{n} | {lh[0] * 1e12:.1f} | {lh[1]} | {hl[0] * 1e12:.1f} | {hl[1]} |")
    print("\nRESULT:", "PASS" if not bad else f"FAIL ({bad})")
    return 1 if bad else 0


def devices(insts, num):
    """[(master, nodes, w, l)] with w/l in metres; other multiplicity params must be 1."""
    out = []
    for name, master, nodes, p in insts:
        for k in ("m", "nf", "fingers", "mult"):
            if k in p and num(p[k]) != 1:
                raise ValueError(f"{name}: {k}={p[k]}")
        # the gpdk090 CDF netlists the finger width as w (simW = fw); 1 finger checked above
        w, l = (round(num(p[k]) * 1e12) if k in p else None for k in ("w", "l"))
        out.append((master.replace("gpdk090_", ""), tuple(nodes), w, l))
    return sorted(out)


def sbnet(log, pins_of):
    """SB_NET lines of out/sch/gen.log (schCheck connectivity) -> {cell: [inst tuples like parse()]}."""
    cells = {}
    for line in open(log, encoding="ascii", errors="replace"):
        if not line.startswith("SB_NET "):
            continue
        tok = line.split()
        cell, inst, master = tok[1:4]
        kv = dict(t.split("=", 1) for t in tok[4:])
        if master in ("nmos1v", "pmos1v"):
            nodes = [kv[t] for t in ("D", "G", "S", "B")]
            par = {k: kv[k].strip('"') for k in ("fw", "l", "m", "fingers") if kv.get(k, "nil") != "nil"}
            par["w"] = par.pop("fw")        # fw is what the CDF netlists as w
        else:
            nodes, par = [kv[t] for t in pins_of(master)], {}
        cells.setdefault(cell, []).append((inst, master, nodes, par))
    return cells


def same(ref, insts, num):
    """True if insts match ref['insts'] up to a renaming of internal nets."""
    import itertools
    exp = devices(ref["insts"], num)
    have = devices(insts, num)
    ext = set(ref["pins"])
    ints_e = sorted({n for _, ns, _, _ in exp for n in ns} - ext)
    ints_h = sorted({n for _, ns, _, _ in have for n in ns} - ext)
    if have == exp:          # scs2skill giu ten net noi bo: so thang, khong can hoan vi
        return True
    if len(ints_e) != len(ints_h) or len(ints_e) > 8:
        return False
    for perm in itertools.permutations(ints_e):
        m = dict(zip(ints_h, perm))
        if sorted((a, tuple(m.get(n, n) for n in ns), w, l) for a, ns, w, l in have) == exp:
            return True
    return False


def netcmp():
    """Compare each schematic with cells/*/<CELL>.scs using the schCheck connectivity dump
    (SB_NET in out/sch/gen.log). `si -batch` netlisting hangs in this VM, so it is not used."""
    sys.path.insert(0, str(ROOT / "tools"))
    from scs2skill import parse, num
    refs = {c: parse(ROOT / d / c / f"{c}.scs")[c] for c, (d, _) in CELLS.items()}
    log = OUT.parent / "sch" / "gen.log"
    dump = sbnet(log, lambda m: refs[m]["pins"]) if log.exists() else {}
    bad = 0
    for cell, ref in refs.items():
        res = []
        for src, insts in (("schCheck-dump", dump.get(cell)),):
            try:
                ok = insts is not None and same(ref, insts, num)
            except (ValueError, KeyError) as e:
                ok = False
                print(f"  {cell} {src}: {e}")
            res.append(f"{src}={'OK' if ok else 'MISSING' if insts is None else 'FAIL'}")
            bad += not ok
        print(f"{cell}: {len(ref['insts'])} devices/instances  " + "  ".join(res))
    print("RESULT:", "PASS" if not bad else f"FAIL ({bad})")
    return 1 if bad else 0


def bundle(out, command):
    """Write a job script that carries cells/ and skill/ inside itself (heredocs), unpacks them
    to /tmp and runs `command` there with OUTD=<VLSI_work>/out. The VM's hgfs mount can serve
    stale content of files changed on Windows; a new job file is always read fresh."""
    L = ["B=/tmp/a_bundle_$$", 'rm -rf "$B"', 'mkdir -p "$B"', "export OUTD=$PWD/out"]
    for f in sorted(p for d in ("cells", "skill") for p in (ROOT / d).rglob("*") if p.is_file()):
        rel = f.relative_to(ROOT).as_posix()
        if f.suffix not in (".scs", ".il", ".sh"):
            continue
        L += [f'mkdir -p "$B/{os.path.dirname(rel)}"', f"cat > \"$B/{rel}\" <<'__A_BUNDLE_EOF__'",
              f.read_text(encoding="ascii").rstrip("\n"), "__A_BUNDLE_EOF__"]
    L += ['cd "$B" && ' + command, "rc=$?", 'rm -rf "$B"', "exit $rc", ""]
    Path(out).write_text("\n".join(L), encoding="ascii", newline="\n")


if __name__ == "__main__":
    cmd = sys.argv[1] if len(sys.argv) > 1 else ""
    if cmd == "gen":
        gen()
    elif cmd == "bundle":       # check_cells.py bundle <out.sh> "<command>"
        bundle(sys.argv[2], sys.argv[3])
    elif cmd == "check":
        sys.exit(check())
    elif cmd == "netcmp":
        sys.exit(netcmp())
    else:
        sys.exit(__doc__)
