#!/usr/bin/env python3
"""cells/A/<CELL>/<CELL>.scs -> layout/assura/cdl/<CELL>.cdl (LVS source for Assura). Runs on Windows.

    python layout/scs2cdl.py

One CDL file per cell, holding that subckt plus every subckt it instantiates
(leaves first). MOS lines keep the Spectre w=/l= values, e.g.
    MN0 Y A VSS VSS nmos1v w=0.12u l=0.1u
"""
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO / "tools"))
from scs2skill import PRIM, collect  # noqa: E402  (same .scs parser as the schematic generator)

OUT = REPO / "layout" / "assura" / "cdl"


def deps(cells, name, seen):
    for _, master, _, _ in cells[name]["insts"]:
        if master not in PRIM and master not in seen:
            deps(cells, master, seen)
    seen.setdefault(name, None)
    return seen


def subckt(name, c):
    lines = [f".SUBCKT {name} {' '.join(c['pins'])}"]
    for inst, master, nodes, params in c["insts"]:
        if master in PRIM:
            kv = " ".join(f"{k}={params[k]}" for k in ("w", "l"))
            # device name as Assura extracts it: PRIM value[1] (nmos1v), or the bare master
            dev = PRIM[master][1] if len(PRIM[master]) == 3 else master
            lines.append(f"{inst} {' '.join(nodes)} {dev} {kv}")
        else:
            lines.append(f"{inst} {' '.join(nodes)} {master}")
    return lines + [f".ENDS {name}", ""]


def main():
    cells = collect("ALU_CELLS_A=" + str(REPO / "cells" / "A"))
    OUT.mkdir(parents=True, exist_ok=True)
    for name in cells:
        text = [f"* {name}: generated by layout/scs2cdl.py from cells/A -- do not edit", ""]
        for d in deps(cells, name, {}):
            text += subckt(d, cells[d])
        (OUT / f"{name}.cdl").write_text("\n".join(text), encoding="ascii", newline="\n")
        print("wrote", (OUT / f"{name}.cdl").relative_to(REPO))
    assert "MN0 Y A VSS VSS nmos1v w=0.12u l=0.1u" in (OUT / "INV_X1.cdl").read_text()


if __name__ == "__main__":
    main()
