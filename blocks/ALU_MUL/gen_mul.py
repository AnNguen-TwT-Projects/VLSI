#!/usr/bin/env python3
"""Signed 8x8 -> 16 bit multiplier MUL8 (B + C), runs on Windows (Python 3 stdlib).

    python blocks/ALU_MUL/gen_mul.py            # write cells (cells/B, cells/C), MUL8.scs, tb
    python blocks/ALU_MUL/gen_mul.py --check    # gate-level check, all 65536 (a, b)
    python blocks/ALU_MUL/gen_mul.py --count    # transistor count + cell depth
    python blocks/ALU_MUL/gen_mul.py --result out/MUL8_NN   # compare Spectre psfascii

Architecture (docs/KE_HOACH_ALU.md "Nhan co dau", rows as model/alu_ref.booth_pp_rows):
  4x BOOTH_ENC + 36x BOOTH_SEL -> 4 rows (sign-extension elimination, neg_i in row i+1)
  stage 1: 4:2 compressors (CMP42 chain cols 6..12) + FA/HA  -> height <= 3 (only col 4 = 3)
  stage 2: FA at col 4, HA above (carry-save)                -> 2 rows
  final:   ripple FA/HA for P_0..7, KSA8 of A (blocks/ALU_ADD) for P_8..15, CIN = ripple carry
Reuses blocks/gen_blocks.py (Block, FUNC simulator) and blocks/gen_tb.py / check_results.py.
"""
