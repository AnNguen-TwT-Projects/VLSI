# ---------------------------------------------------------------- transistor-level cells
class Cell:
    """Flat static-CMOS cell; sizes per CONVENTIONS section 3 (unit n 0.12u / p 0.24u, x stack)."""

    def __init__(self, name, d, pins, doc):
        self.name, self.dir, self.pins, self.doc, self.L, self.k = name, d, pins, doc, [], 0

    def m(self, t, d, g, s, w):
        self.k += 1
        self.L.append(f'    M{t.upper()}{self.k} ({d} {g} {s} {"VSS" if t == "n" else "VDD"}) '
                      f'gpdk090_{t}mos1v w={w:g}u l=0.1u')

    def inv(self, a, y):
        self.m('n', y, a, 'VSS', 0.12)
        self.m('p', y, a, 'VDD', 0.24)

    def xor(self, a, b, y, p, xnor=False):
        """12T like the XOR2/XNOR2 stubs: input inverters + Y = !(A&B1 | An&B2)."""
        an, bn = p + 'an', p + 'bn'
        self.inv(a, an)
        self.inv(b, bn)
        b1, b2 = (bn, b) if xnor else (b, bn)
        self.m('n', y, a, p + 'n1', 0.24); self.m('n', p + 'n1', b1, 'VSS', 0.24)
        self.m('n', y, an, p + 'n2', 0.24); self.m('n', p + 'n2', b2, 'VSS', 0.24)
        self.m('p', p + 'p1', a, 'VDD', 0.48); self.m('p', p + 'p1', b1, 'VDD', 0.48)
        self.m('p', y, an, p + 'p1', 0.48); self.m('p', y, b2, p + 'p1', 0.48)

    def nand2(self, a, b, y, p):
        self.m('n', y, a, p + 'n', 0.24); self.m('n', p + 'n', b, 'VSS', 0.24)
        self.m('p', y, a, 'VDD', 0.24); self.m('p', y, b, 'VDD', 0.24)

    def nor2(self, a, b, y, p):
        self.m('n', y, a, 'VSS', 0.12); self.m('n', y, b, 'VSS', 0.12)
        self.m('p', p + 'p', a, 'VDD', 0.48); self.m('p', y, b, p + 'p', 0.48)

    def fa(self, a, b, c, s, co, p):
        """28T mirror adder: CON = !maj, SN = !(ABC + CON(A+B+C)), S = !SN, CO = !CON."""
        con, sn = p + 'con', p + 'sn'
        for t, r, w2, w3 in (('n', 'VSS', 0.24, 0.36), ('p', 'VDD', 0.48, 0.72)):
            q = p + t
            self.m(t, q + '1', a, r, w2); self.m(t, con, b, q + '1', w2)            # A.B
            self.m(t, q + '2', a, r, w2); self.m(t, q + '2', b, r, w2)
            self.m(t, con, c, q + '2', w2)                                           # C.(A+B)
            for x in (a, b, c):
                self.m(t, q + '3', x, r, w2)
            self.m(t, sn, con, q + '3', w2)                                          # CON.(A+B+C)
            self.m(t, q + '4', a, r, w3); self.m(t, q + '5', b, q + '4', w3)
            self.m(t, sn, c, q + '5', w3)                                            # A.B.C
        self.inv(sn, s)
        self.inv(con, co)

    def text(self):
        return '\n'.join([f'// {self.name} (owner {self.dir.split("/")[-1]}): generated by '
                          'blocks/ALU_MUL/gen_mul.py - do not edit by hand',
                          f'// {self.doc}', f'// Pins: {" ".join(self.pins)} VDD VSS. {self.k} transistors.',
                          'simulator lang=spectre', f'subckt {self.name} {" ".join(self.pins)} VDD VSS']
                         + self.L + [f'ends {self.name}', ''])

    @property
    def path(self):
        return f'{self.dir}/{self.name}/{self.name}.scs'


def make_cells():
    c = []
    x = Cell('FA_X1', 'cells/C', ['A', 'B', 'CI', 'S', 'CO'], 'S = A^B^CI, CO = maj(A,B,CI). 28T mirror adder.')
    x.fa('A', 'B', 'CI', 'S', 'CO', '')
    c.append(x)
    x = Cell('INV_X4', 'cells/C', ['A', 'Y'], 'Buffer (C): inverter 4x INV_X1 (n 0.48u / p 0.96u), '
             'drives the high-fanout q net of each DIV8 row (docs/sizing.md).')
    x.m('n', 'Y', 'A', 'VSS', 0.48)
    x.m('p', 'Y', 'A', 'VDD', 0.96)
    c.append(x)
    x = Cell('HA_X1', 'cells/C', ['A', 'B', 'S', 'CO'], 'S = A^B (XOR2 12T), CO = A&B (NAND2+INV).')
    x.xor('A', 'B', 'S', 'x')
    x.nand2('A', 'B', 'con', 'a')
    x.inv('con', 'CO')
    c.append(x)
    x = Cell('BOOTH_ENC', 'cells/B', ['X2', 'X1', 'X0', 'ONE', 'TWO'],
             'Radix-4 Booth encoder (X2,X1,X0) = (b2i+1,b2i,b2i-1): ONE = X1^X0, '
             'TWO = !(XNOR(X2,X1) | ONE). NEG = X2 (wire).')
    x.xor('X1', 'X0', 'ONE', 'a')
    x.xor('X2', 'X1', 'e', 'b', xnor=True)
    x.nor2('e', 'ONE', 'TWO', 'c')
    c.append(x)
    x = Cell('BOOTH_SEL', 'cells/B', ['AJ', 'AJM', 'ONE', 'TWO', 'NEG', 'PP'],
             'Booth selector: PP = (ONE&AJ | TWO&AJM) ^ NEG = XNOR(AOI22, NEG).')
    x.m('n', 'xn', 'ONE', 'n1', 0.24); x.m('n', 'n1', 'AJ', 'VSS', 0.24)
    x.m('n', 'xn', 'TWO', 'n2', 0.24); x.m('n', 'n2', 'AJM', 'VSS', 0.24)
    x.m('p', 'p1', 'ONE', 'VDD', 0.48); x.m('p', 'p1', 'AJ', 'VDD', 0.48)
    x.m('p', 'xn', 'TWO', 'p1', 0.48); x.m('p', 'xn', 'AJM', 'p1', 0.48)
    x.xor('xn', 'NEG', 'PP', 'x', xnor=True)
    c.append(x)
    x = Cell('CMP42', 'cells/B', ['X1', 'X2', 'X3', 'X4', 'CI', 'S', 'C', 'CO'],
             '4:2 compressor = 2 mirror FAs (flat): FA(X1,X2,X3) -> s1, CO; FA(s1,X4,CI) -> S, C. '
             'X1+X2+X3+X4+CI = S + 2(C+CO); CO does not depend on CI.')
    x.fa('X1', 'X2', 'X3', 's1', 'CO', 'a')
    x.fa('s1', 'X4', 'CI', 'S', 'C', 'b')
    c.append(x)
    return c


def maj(a, b, c):
    return a & b | a & c | b & c


def _cmp42(x1, x2, x3, x4, ci):
    s1 = x1 ^ x2 ^ x3
    return s1 ^ x4 ^ ci, maj(s1, x4, ci), maj(x1, x2, x3)


gb.FUNC.update({
    'FA_X1': lambda a, b, c: (a ^ b ^ c, maj(a, b, c)),
    'HA_X1': lambda a, b: (a ^ b, a & b),
    'INV_X4': lambda a: (nt(a),),
    'BOOTH_ENC': lambda x2, x1, x0: (x1 ^ x0, nt(nt(x2 ^ x1) | (x1 ^ x0))),
    'BOOTH_SEL': lambda aj, ajm, one, two, neg: ((one & aj | two & ajm) ^ neg,),
    'CMP42': _cmp42,
})


# ---------------------------------------------------------------- MUL8
def gen_mul8():
    gb.build()                                   # A's blocks (KSA8 is reused)
    if 'MUL8' in gb.BLOCKS:
        return gb.BLOCKS['MUL8']
    A, B, P = bus('A', 8), bus('B', 8), bus('P', 16)
    m = Block('MUL8', 'blocks/ALU_MUL/MUL8.scs', A + B, P)
    cols = [[] for _ in range(16)]

    def put(j, n):
        if j < 16:                               # bit 16 (row 3's constant 1) is dropped
            cols[j].append(n)

    aj = lambda j: 'VSS' if j < 0 else A[min(j, 7)]   # a_-1 = 0, a_8 = a_7 (9-bit sign ext.)
    for i in range(4):
        one, two = m.x('BOOTH_ENC', [B[2 * i + 1], B[2 * i], B[2 * i - 1] if i else 'VSS'],
                       [f'one{i}', f'two{i}'])
        pp = [m.x('BOOTH_SEL', [aj(j), aj(j - 1), one, two, B[2 * i + 1]], f'pp{i}_{j}') for j in range(9)]
        sn = m.x('INV_X1', [pp[8]], f'sn{i}')
        if i:
            put(2 * i - 2, B[2 * i - 1])         # neg_{i-1} in the empty slot of row i
        for k, n in enumerate(pp + ([pp[8], pp[8], sn] if i == 0 else [sn, 'VDD'])):
            put(2 * i + k, n)
    put(6, B[7])                                 # neg_3: extra bit at column 6
    nid = [0]

    def cell(master, ins, nout):
        nid[0] += 1
        return m.x(master, ins, [f'{master[:2].lower()}{nid[0]}_{k}' for k in range(nout)])

    # stage 1: 4:2 compressors where the column (+ CO from the left) has 4-5 bits
    out, co = [[] for _ in range(17)], None
    for j in range(16):
        L, k = cols[j] + ([co] if co else []), len(out[j])
        had_ci, co = co is not None, None
        if len(L) + k <= 2:
            out[j] += L
        elif len(L) == 2:
            s, c = cell('HA_X1', L, 2); out[j].append(s); out[j + 1].append(c)
        elif len(L) == 3:
            s, c = cell('FA_X1', L, 2); out[j].append(s); out[j + 1].append(c)
        elif len(L) == 4 and not had_ci:          # no CO chain into this column: FA + pass
            s, c = cell('FA_X1', L[:3], 2); out[j] += [s, L[3]]; out[j + 1].append(c)
        elif len(L) in (4, 5):                    # CI = last (the late CO from the left)
            L = L[:-1] + ['VSS'] * (5 - len(L)) + L[-1:]
            s, c, co = cell('CMP42', L, 3); out[j].append(s); out[j + 1].append(c)
        else:
            raise AssertionError(f'stage 1 col {j}: {len(L)} bits')
    assert max(map(len, out[:16])) <= 3, out
    # stage 2: carry-save FA/HA -> 2 rows
    out2 = [[] for _ in range(17)]
    for j in range(16):
        L, k = out[j], len(out2[j])
        if len(L) + k <= 2:
            out2[j] += L
        else:
            s, c = cell({2: 'HA_X1', 3: 'FA_X1'}[len(L)], L, 2); out2[j].append(s); out2[j + 1].append(c)
    assert max(map(len, out2[:16])) <= 2, out2
    # final adder: ripple for P_0..7 (early columns), KSA8 for P_8..15
    c, ren = None, {}
    for j in range(8):
        L = out2[j] + ([c] if c else [])
        if len(L) == 1:
            ren[L[0]] = P[j]; c = None
        else:
            s, c = m.x({2: 'HA_X1', 3: 'FA_X1'}[len(L)], L, [P[j], f'rc{j + 1}'])
    hi = [out2[j] + ['VSS'] * (2 - len(out2[j])) for j in range(8, 16)]
    m.x('KSA8', [h[0] for h in hi] + [h[1] for h in hi] + [c or 'VSS'], P[8:] + ['kc7', 'kc8'])
    assert not set(ren) & set(A + B + ['VDD', 'VSS'])
    m.insts = [(ms, [ren.get(n, n) for n in i], [ren.get(n, n) for n in o]) for ms, i, o in m.insts]
    m.cols, m.out1, m.out2 = [len(x) for x in cols], [len(x) for x in out[:16]], [len(x) for x in out2[:16]]
    return m


def mul_ref(a, b):
    return (s8(a) * s8(b)) & 0xFFFF


def run_mul(m, a, b):
    v = m.run({**dict(zip(m.ins, bits(a, 8) + bits(b, 8))), 'VDD': 1, 'VSS': 0})
    return val([v[p] for p in m.outs])


def check():
    m = gen_mul8()
    bad = [(a, b) for a in range(256) for b in range(256) if run_mul(m, a, b) != mul_ref(a, b)]
    print(f'MUL8 gate-level: {65536 - len(bad)}/65536 (a, b) pairs correct' + (f', first bad {bad[:5]}' if bad else ''))
    return 1 if bad else 0


# ---------------------------------------------------------------- count / depth
def files():
    return gb.CELL_FILES + [c.path for c in make_cells()] + ['blocks/ALU_ADD/KSA8.scs', gen_mul8().path]


def depth(blk, din):
    """Cell levels from inputs to each output (sub-blocks expanded)."""
    d = dict(din)
    for ms, i, o in blk.insts:
        di = [d.get(n, 0) for n in i]
        if ms in gb.BLOCKS:
            d.update(zip(o, depth(gb.BLOCKS[ms], dict(zip(gb.BLOCKS[ms].ins, di)))))
        else:
            d.update((x, max(di) + 1) for x in o)
    return [d[x] for x in blk.outs]


def count():
    m = gen_mul8()
    subs = gb.parse_subckts(files())

    def n(x):
        return 1 if x.startswith('gpdk090_') else sum(n(y) for y in subs[x])
    for c in make_cells():
        print(f'{c.name:10s} {n(c.name):5d} T')
    used = {}
    for ms, _, _ in m.insts:
        used[ms] = used.get(ms, 0) + 1
    print('MUL8 instances:', ', '.join(f'{k} x{v}' for k, v in used.items()))
    print(f'MUL8 {n("MUL8")} transistors (KSA8 {n("KSA8")})')
    print('column heights: pp', m.cols, '\n  after 4:2 stage', m.out1, '\n  after FA/HA stage', m.out2)
    d = depth(m, {})
    print('cell depth to P_0..15:', d, 'max', max(d))


# ---------------------------------------------------------------- Spectre testbench
def vectors():
    with (REPO / 'vectors' / 'alu_full.csv').open(newline='') as f:
        v = [(int(r['a']), int(r['b'])) for r in csv.DictReader(f) if int(r['op']) == 9]
    for p in ((128, 128), (128, 127), (127, 128), (0, 0), (255, 255), (0, 128), (127, 127), (255, 1)):
        if p not in v:
            v.append(p)
    rnd = random.Random(8)
    while len(v) < 80:
        v.append((rnd.randrange(256), rnd.randrange(256)))
    return v[:80]


def gen_testbench():
    m = gen_mul8()
    d = HERE / 'tb'
    d.mkdir(exist_ok=True)
    V = vectors()
    with (d / 'mul8_vectors.csv').open('w', newline='') as f:
        f.write('a,b,p\n' + ''.join(f'{a},{b},{mul_ref(a, b)}\n' for a, b in V))
    gen_tb.T = T                                  # pwl() reads the module global
    gen_tb.BENCH['MUL8'] = ('blocks/ALU_MUL/tb', 'blocks/ALU_MUL/tb/mul8_vectors.csv', lambda r: True)
    R = gen_tb.rows('MUL8')
    L = [f'// Testbench MUL8: generated by blocks/ALU_MUL/gen_mul.py ({len(R)} vectors, tb/mul8_vectors.csv)',
         f'// {T * 1e9:g} ns/vector, edges {gen_tb.EDGE * 1e12:g} ps, 4x INV_X1 load per output',
         'simulator lang=spectre', 'global 0', 'VVDD (VDD 0) vsource dc=1.2', 'VVSS (VSS 0) vsource dc=0']
    for p in m.ins:
        c, i = gen_tb.col_bit(p)
        L.append(f'V{p} ({p} 0) vsource type=pwl wave=[ \\\n    {gen_tb.pwl([(int(r[c]) >> i) & 1 for r in R])} ]')
    L.append(f'XDUT ({" ".join(m.ins + m.outs)} VDD VSS) MUL8')
    L += [f'XL{p}_{k} ({p} ld_{p}_{k} VDD VSS) INV_X1' for p in m.outs for k in range(4)]
    L += ['save ' + ' '.join(m.outs) + ' VVDD:p', 'opts options save=selected temp=27 reltol=1e-3',
          f'tran tran stop={len(R) * T * 1e9:g}n maxstep=10p errpreset=moderate']
    (d / 'tb_MUL8.scs').write_text('\n'.join(L) + '\n', encoding='ascii', newline='\n')
    incs = ['cells/A/cells_A.scs'] + [c for c in gb.CELL_FILES if '_stub_B' in c] + \
           [c.path for c in make_cells()] + ['blocks/ALU_ADD/KSA8.scs', m.path]
    for cn in gen_tb.CORNERS:
        w = [f'// MUL8 corner {cn}: generated by blocks/ALU_MUL/gen_mul.py', 'simulator lang=spectre',
             f'include "{MODEL}" section={cn}'] + [f'include "../../../{p}"' for p in incs] + ['include "tb_MUL8.scs"']
        (d / f'tb_MUL8_{cn}.scs').write_text('\n'.join(w) + '\n', encoding='ascii', newline='\n')
    print(f'wrote blocks/ALU_MUL/tb/tb_MUL8.scs ({len(R)} vectors) + {len(gen_tb.CORNERS)} corners')


def result(path):
    import check_results
    gen_mul8()
    check_results.T = T
    gen_tb.BENCH['MUL8'] = ('blocks/ALU_MUL/tb', 'blocks/ALU_MUL/tb/mul8_vectors.csv', lambda r: True)
    sys.argv = ['check_results.py', 'MUL8', path]
    return check_results.main()


def main():
    if '--check' in sys.argv:
        return check()
    if '--count' in sys.argv:
        return count()
    if '--result' in sys.argv:
        return result(sys.argv[sys.argv.index('--result') + 1])
    for c in make_cells():
        p = REPO / c.path
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(c.text(), encoding='ascii', newline='\n')
        print('wrote', c.path, c.k, 'T')
    m = gen_mul8()
    hdr = ('// MUL8: signed 8x8 -> 16 bit, Booth radix-4 + 4:2 tree + ripple/KSA8 final adder.\n'
           '// Generated by blocks/ALU_MUL/gen_mul.py - do not edit by hand.\n'
           '// Needs: cells/A/cells_A.scs, XOR2_X1/XNOR2_X1, cells/B (BOOTH_ENC BOOTH_SEL CMP42),\n'
           '//        cells/C (FA_X1 HA_X1), blocks/ALU_ADD/KSA8.scs\nsimulator lang=spectre\n')
    (REPO / m.path).write_text(hdr + m.scs(), encoding='ascii', newline='\n')
    print('wrote', m.path, len(m.insts), 'instances')
    gen_testbench()


if __name__ == '__main__':
    sys.exit(main())
