#!/usr/bin/env python3
"""Ban co so de so sanh voi MUL8 (Booth): MUL8_DADDA = mang AND Baugh-Wooley + cay Dadda (B).
Chay tren Windows, Python 3 stdlib.

    python blocks/ALU_MUL/gen_dadda.py            # ghi blocks/ALU_MUL/MUL8_DADDA.scs + tb (3 corner)
    python blocks/ALU_MUL/gen_dadda.py --check    # muc logic: 65536 cap (a, b)
    python blocks/ALU_MUL/gen_dadda.py --count    # transistor, so cell, do sau cell (so voi MUL8)
    python blocks/ALU_MUL/gen_dadda.py --result out/MUL8_DADDA_NN

Kien truc:
  64 tich rieng: a_i b_j = AND (NAND2+INV); a_7 b_j, a_i b_7 (i, j < 7) = NAND2 (Baugh-Wooley);
  hang so 1 o cot 8 va cot 15.  Do cao cot toi da 8 -> Dadda 6, 4, 3, 2 (FA/HA cua C).
  Bo cong cuoi giong MUL8: ripple FA/HA cho P_0..7, KSA8 cua A cho P_8..15 -> chi khac cay nen.
Cung vector (tb/mul8_vectors.csv), tai, chu ky nhu MUL8 de so sanh cong bang.
"""
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import gen_mul as gm  # noqa: E402  (FUNC cua FA/HA, mul_ref, depth, cell files)
from gen_mul import REPO, gb, gen_tb, Block, bits, bus, val  # noqa: E402

NAME = 'MUL8_DADDA'
PATH = 'blocks/ALU_MUL/MUL8_DADDA.scs'


def dadda_heights(hmax):
    d = [2]
    while d[-1] * 3 // 2 < hmax:
        d.append(d[-1] * 3 // 2)
    return d[::-1]                                   # 8 -> [6, 4, 3, 2]


def gen_dadda():
    gb.build()
    if NAME in gb.BLOCKS:
        return gb.BLOCKS[NAME]
    A, B, P = bus('A', 8), bus('B', 8), bus('P', 16)
    m = Block(NAME, PATH, A + B, P)
    cols = [[] for _ in range(16)]
    for i in range(8):
        for j in range(8):
            n = m.x('NAND2_X1', [A[i], B[j]], f'pn{i}_{j}')
            cols[i + j].append(n if (i == 7) != (j == 7) else m.x('INV_X1', [n], f'pp{i}_{j}'))
    cols[8].append('VDD')
    cols[15].append('VDD')
    m.cols = [len(c) for c in cols]
    nid = [0]

    def cell(master, ins):
        nid[0] += 1
        return m.x(master, ins, [f'd{nid[0]}_s', f'd{nid[0]}_c'])

    for d in dadda_heights(max(m.cols)):
        nxt = [[] for _ in range(17)]
        for j in range(16):
            L = list(cols[j])
            while len(L) + len(nxt[j]) > d:
                over = len(L) + len(nxt[j]) - d
                k = 2 if over == 1 else 3
                assert len(L) >= k, (d, j, L, nxt[j])
                s, c = cell({2: 'HA_X1', 3: 'FA_X1'}[k], L[:k])
                L = L[k:]
                nxt[j].append(s)
                nxt[j + 1].append(c)
            nxt[j] += L
        cols = nxt[:16]                              # cot 16 = bit tran, bo (mod 2^16)
    assert max(map(len, cols)) <= 2, cols
    m.out2 = [len(c) for c in cols]
    # bo cong cuoi: y het gen_mul.gen_mul8
    c, ren = None, {}
    for j in range(8):
        L = cols[j] + ([c] if c else [])
        if len(L) == 1:
            ren[L[0]] = P[j]
            c = None
        else:
            s, c = m.x({2: 'HA_X1', 3: 'FA_X1'}[len(L)], L, [P[j], f'rc{j + 1}'])
    assert not set(ren) & set(A + B + ['VDD', 'VSS'])
    hi = [cols[j] + ['VSS'] * (2 - len(cols[j])) for j in range(8, 16)]
    m.x('KSA8', [h[0] for h in hi] + [h[1] for h in hi] + [c or 'VSS'], P[8:] + ['kc7', 'kc8'])
    m.insts = [(ms, [ren.get(n, n) for n in i], [ren.get(n, n) for n in o]) for ms, i, o in m.insts]
    gb.BLOCKS[NAME] = m
    return m


def run(m, a, b):
    v = m.run({**dict(zip(m.ins, bits(a, 8) + bits(b, 8))), 'VDD': 1, 'VSS': 0})
    return val([v[p] for p in m.outs])


def check():
    m = gen_dadda()
    bad = [(a, b) for a in range(256) for b in range(256) if run(m, a, b) != gm.mul_ref(a, b)]
    print(f'{NAME} gate-level: {65536 - len(bad)}/65536 (a, b) pairs correct' + (f', first bad {bad[:5]}' if bad else ''))
    return 1 if bad else 0


def count():
    gm.gen_mul8()
    m = gen_dadda()
    subs = gb.parse_subckts(gm.files() + [PATH])

    def n(x):
        return 1 if x.startswith('gpdk090_') else sum(n(y) for y in subs[x])
    for blk in (gb.BLOCKS['MUL8'], m):
        used = {}
        for ms, _, _ in blk.insts:
            used[ms] = used.get(ms, 0) + 1
        d = gm.depth(blk, {})
        print(f'{blk.name:11s} {n(blk.name):5d} T, cell depth max {max(d)}; ' + ', '.join(f'{k} x{v}' for k, v in used.items()))
    print('Dadda: column heights', m.cols, '-> stages', dadda_heights(max(m.cols)), '-> rows', m.out2)
    return 0


def gen_testbench(m):
    d = HERE / 'tb'
    gen_tb.T = gm.T
    gen_tb.BENCH[NAME] = ('blocks/ALU_MUL/tb', 'blocks/ALU_MUL/tb/mul8_vectors.csv', lambda r: True)
    R = gen_tb.rows(NAME)
    L = [f'// Testbench {NAME}: generated by blocks/ALU_MUL/gen_dadda.py ({len(R)} vectors, tb/mul8_vectors.csv)',
         f'// {gm.T * 1e9:g} ns/vector, edges {gen_tb.EDGE * 1e12:g} ps, 4x INV_X1 load per output (nhu MUL8)',
         'simulator lang=spectre', 'global 0', 'VVDD (VDD 0) vsource dc=1.2', 'VVSS (VSS 0) vsource dc=0']
    for p in m.ins:
        c, i = gen_tb.col_bit(p)
        L.append(f'V{p} ({p} 0) vsource type=pwl wave=[ \\\n    {gen_tb.pwl([(int(r[c]) >> i) & 1 for r in R])} ]')
    L.append(f'XDUT ({" ".join(m.ins + m.outs)} VDD VSS) {NAME}')
    L += [f'XL{p}_{k} ({p} ld_{p}_{k} VDD VSS) INV_X1' for p in m.outs for k in range(4)]
    L += ['save ' + ' '.join(m.outs) + ' VVDD:p', 'opts options save=selected temp=27 reltol=1e-3',
          f'tran tran stop={len(R) * gm.T * 1e9:g}n maxstep=10p errpreset=moderate']
    (d / f'tb_{NAME}.scs').write_text('\n'.join(L) + '\n', encoding='ascii', newline='\n')
    incs = ['cells/A/cells_A.scs'] + [c for c in gb.CELL_FILES if '_stub_B' in c] + \
           [c.path for c in gm.make_cells() if c.dir == 'cells/C'] + ['blocks/ALU_ADD/KSA8.scs', PATH]
    for cn in gen_tb.CORNERS:
        w = [f'// {NAME} corner {cn}: generated by blocks/ALU_MUL/gen_dadda.py', 'simulator lang=spectre',
             f'include "{gm.MODEL}" section={cn}'] + [f'include "../../../{p}"' for p in incs] + [f'include "tb_{NAME}.scs"']
        (d / f'tb_{NAME}_{cn}.scs').write_text('\n'.join(w) + '\n', encoding='ascii', newline='\n')
    print(f'wrote blocks/ALU_MUL/tb/tb_{NAME}.scs ({len(R)} vectors) + {len(gen_tb.CORNERS)} corners')


def result(path):
    import check_results
    gen_dadda()
    check_results.T = gm.T
    gen_tb.BENCH[NAME] = ('blocks/ALU_MUL/tb', 'blocks/ALU_MUL/tb/mul8_vectors.csv', lambda r: True)
    sys.argv = ['check_results.py', NAME, path]
    return check_results.main()


def main():
    if '--check' in sys.argv:
        return check()
    if '--count' in sys.argv:
        return count()
    if '--result' in sys.argv:
        return result(sys.argv[sys.argv.index('--result') + 1])
    m = gen_dadda()
    hdr = (f'// {NAME}: signed 8x8 -> 16 bit, Baugh-Wooley AND array + Dadda tree + ripple/KSA8 (baseline).\n'
           '// Generated by blocks/ALU_MUL/gen_dadda.py - do not edit by hand.\n'
           '// Needs: cells/A/cells_A.scs, XOR2_X1/XNOR2_X1, cells/C (FA_X1 HA_X1), blocks/ALU_ADD/KSA8.scs\n'
           'simulator lang=spectre\n')
    (REPO / PATH).write_text(hdr + m.scs(), encoding='ascii', newline='\n')
    print('wrote', PATH, len(m.insts), 'instances')
    gen_testbench(m)
    return 0


if __name__ == '__main__':
    sys.exit(main())
